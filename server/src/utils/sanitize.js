/**
 * Sanitize text to prevent Cross-Site Scripting (XSS)
 * Escapes HTML characters: &, <, >, ", '
 */
export const sanitizeHtml = (str) => {
  if (typeof str !== 'string') return '';
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#x27;')
    .replace(/\//g, '&#x2F;');
};

